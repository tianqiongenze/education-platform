package com.ep.business.course;

import com.ep.business.RepositoryTestSupport;
import com.ep.business.common.SnowflakeIdGenerator;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.data.jpa.test.autoconfigure.DataJpaTest;
import org.springframework.context.annotation.Import;
import org.springframework.data.domain.PageRequest;
import org.springframework.test.context.TestPropertySource;

import java.math.BigDecimal;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * {@code @DataJpaTest} slice tests for {@link CourseRepository}. Exercises the
 * Spring-Data-derived finders (paginated list + title-contains search) and the
 * base {@code save}/{@code findById} against an in-memory H2 database in MySQL
 * compatibility mode (DDL is auto-generated by Hibernate from the entity).
 */
@DataJpaTest
@Import(RepositoryTestSupport.class)
@TestPropertySource(properties = {
        // H2 in MySQL mode so TiDB/MySQL-specific column types (BIGINT, DECIMAL)
        // map cleanly during the auto-generated DDL.
        "spring.datasource.url=jdbc:h2:mem:ep_course_test;MODE=MySQL;DB_CLOSE_DELAY=-1",
        "spring.datasource.driver-class-name=org.h2.Driver",
        "spring.jpa.hibernate.ddl-auto=create-drop",
        "spring.jpa.properties.hibernate.dialect=org.hibernate.dialect.H2Dialect",
        // D-132: keep the slice test off the network — Dubbo's default Nacos
        // registry lookup otherwise fails to load the ApplicationContext when no
        // Nacos server is reachable in CI/local dev.
        "dubbo.registry.address=N/A"
})
class CourseRepositoryTest {

    @Autowired
    private CourseRepository repository;

    private Course newCourse(String title, Long teacherId) {
        Course c = new Course();
        // D-132: application-assigned Snowflake id (the entity no longer uses
        // @GeneratedValue IDENTITY — see Course).
        c.setCourseId(SnowflakeIdGenerator.getInstance().nextId());
        c.setTitle(title);
        c.setDescription("desc");
        c.setTeacherId(teacherId);
        c.setCategory(1);
        c.setDifficulty(2);
        c.setPrice(new BigDecimal("99.00"));
        c.setStatus(CourseStatus.DRAFT.getCode());
        c.setStudentCount(0);
        c.setCreatedAt(System.currentTimeMillis());
        c.setUpdatedAt(System.currentTimeMillis());
        return c;
    }

    @Test
    void save_assignsIdAndPersists() {
        Course saved = repository.save(newCourse("Java Basics", 100L));

        assertNotNull(saved.getCourseId());
        assertTrue(repository.findById(saved.getCourseId()).isPresent());
    }

    @Test
    void findAllByOrderByCourseIdAsc_returnsPaginated() {
        for (int i = 0; i < 12; i++) {
            repository.save(newCourse("C" + i, (long) i));
        }

        List<Course> page1 = repository.findAllByOrderByCourseIdAsc(PageRequest.of(0, 10)).getContent();
        List<Course> page2 = repository.findAllByOrderByCourseIdAsc(PageRequest.of(1, 10)).getContent();

        assertEquals(10, page1.size());
        assertEquals(2, page2.size());
        // Ascending order: first id < last id within page 1.
        assertTrue(page1.get(0).getCourseId() < page1.get(9).getCourseId());
    }

    @Test
    void findByTitleContainingOrderByCourseIdAsc_matchesSubstring() {
        repository.save(newCourse("Spring Boot Guide", 1L));
        repository.save(newCourse("Advanced Spring", 1L));
        repository.save(newCourse("Unrelated Physics", 2L));

        List<Course> hits = repository.findByTitleContainingOrderByCourseIdAsc("Spring");

        assertEquals(2, hits.size());
        assertTrue(hits.stream().allMatch(c -> c.getTitle().contains("Spring")));
    }

    @Test
    void findByTitleContainingOrderByCourseIdAsc_noMatchReturnsEmpty() {
        repository.save(newCourse("Spring Boot", 1L));

        List<Course> hits = repository.findByTitleContainingOrderByCourseIdAsc("Quantum");

        assertNotNull(hits);
        assertTrue(hits.isEmpty());
    }

    @Test
    void deleteById_removesCourse() {
        Course saved = repository.save(newCourse("ToDelete", 1L));
        Long id = saved.getCourseId();

        repository.deleteById(id);

        assertFalse(repository.findById(id).isPresent());
    }
}
