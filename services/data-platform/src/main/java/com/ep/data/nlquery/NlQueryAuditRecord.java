package com.ep.data.nlquery;

import java.time.LocalDateTime;

/**
 * Audit record for a single NL Query invocation (D-190).
 *
 * <p>Written to the {@code audit.nl_query_log} Iceberg table in production,
 * or held in-memory in dev/CI. Captures the full audit trail required by
 * §12.4.5 for compliance and replay.
 *
 * <p>Implemented as a Java record per D-040 (GraalVM AOT compatible).
 *
 * @param userId        user who submitted the query
 * @param sessionId     conversation session id (may be null/blank)
 * @param question      original natural-language question
 * @param intent        classified intent (查询/统计/趋势/对比)
 * @param generatedSql  SQL generated by the LLM
 * @param isValid       whether the SQL passed validation
 * @param violations    validation violation reasons (empty when valid)
 * @param executed      whether the SQL was executed against Trino
 * @param rowCount      number of rows returned (0 if not executed)
 * @param latencyMs     end-to-end pipeline latency in milliseconds
 * @param timestamp     when the query was submitted
 */
public record NlQueryAuditRecord(
        String userId,
        String sessionId,
        String question,
        String intent,
        String generatedSql,
        boolean isValid,
        String violations,
        boolean executed,
        int rowCount,
        long latencyMs,
        LocalDateTime timestamp
) {
}
